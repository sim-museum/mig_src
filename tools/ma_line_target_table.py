#!/usr/bin/env python3
"""MA-RED-ALL-1 (c): map each rail/road LINE target UID (UID_RAIL_A2B, UID_ROAD_A2B) to a POINT UID at a town
on it -- the Red flight is placed at its target, and a line has no single position ('Unresolved UIDS').
Prefers B's station (UID_St<B>), then B's marshalling yard / any B point, then the same for A.
  ma_line_target_table.py SRC/H/UIDVALS.G > SRC/BFIELDS/MA_LINETGT.INC"""
import re, sys
src = open(sys.argv[1], encoding='latin-1').read()
uids = dict(re.findall(r'\b(UID_\w+)\s*=\s*(0x[0-9a-fA-F]+)', src))
val = {k: int(v, 16) for k, v in uids.items()}
pts = {k: v for k, v in val.items() if v >= 0x0E00 and not k.startswith(('UID_RAIL_', 'UID_ROAD_'))}
def point(town):
    for pre in ('UID_St', 'UID_My'):
        for k in pts:
            if k.startswith(pre) and k[len(pre):].lstrip('BlRlRdAf').lower() == town.lower(): return k
    c = [k for k in pts if k.lower().endswith(town.lower())]
    return sorted(c)[0] if c else None
print('/* generated by tools/ma_line_target_table.py -- rail/road line UID -> a point UID on it */')
miss = 0
for k in sorted(val, key=val.get):
    m = re.match(r'UID_(RAIL|ROAD)_(\w+?)2(\w+)$', k)
    if not m: continue
    p = point(m.group(3)) or point(m.group(2))
    if p: print('\t{ %s, %s },' % (k, p))
    else: miss += 1; print('\t/* %s: no point UID for %s or %s */' % (k, m.group(2), m.group(3)))
print('/* %d unmatched */' % miss)
